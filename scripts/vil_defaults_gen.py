#!/usr/bin/env python3
"""Compile this board's Vial backup into editable firmware reset defaults."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ALIASES = {
    'KC_LSHIFT': 'KC_LSFT', 'KC_LCTRL': 'KC_LCTL', 'KC_RCTRL': 'KC_RCTL',
    'KC_NONUS_BSLASH': 'KC_NUBS', 'KC_SCOLON': 'KC_SCLN',
    'KC_BSLASH': 'KC_BSLS', 'KC_BSPACE': 'KC_BSPC',
    'KC_LBRACKET': 'KC_LBRC', 'KC_RBRACKET': 'KC_RBRC', 'KC_PGDOWN': 'KC_PGDN',
}


def keycode(value):
    if value == -1:
        return 'KC_NO'  # Unwired matrix position.
    if not isinstance(value, str) or not re.fullmatch(r'[A-Za-z0-9_(), ]+', value):
        raise ValueError(f'Unsupported keycode: {value!r}')
    value = re.sub(r'\b[A-Z][A-Z0-9_]*\b', lambda m: ALIASES.get(m[0], m[0]), value)
    return re.sub(r'\bLT(\d+)\(', r'LT(\1, ', value)


def generate(raw):
    data = json.loads(raw)
    if data['version'] != 1 or data['uid'] != 5010774632021243529:
        raise ValueError('Expected a version-1 BORNE m57 backup')
    expected = {'version', 'uid', 'layout', 'encoder_layout', 'layout_options',
                'macro', 'vial_protocol', 'via_protocol', 'tap_dance', 'combo',
                'key_override', 'alt_repeat_key', 'settings'}
    if set(data) != expected:
        raise ValueError('Unexpected backup fields; review before generating')
    if data['layout_options'] != -1:
        raise ValueError('This board has no configurable layout options')
    # This backup has no macros. Fail rather than silently discard future ones.
    if data['macro'] != [[] for _ in range(15)]:
        raise ValueError('Nonempty macros need an explicit macro-data implementation')
    if len(data['layout']) != 10 or any(len(layer) != 10 or any(len(row) != 7 for row in layer) for layer in data['layout']):
        raise ValueError('Expected 10 layers of a 10x7 matrix')
    if len(data['encoder_layout']) != 10 or any(len(layer) != 2 or any(len(pair) != 2 for pair in layer) for layer in data['encoder_layout']):
        raise ValueError('Expected two encoders on each of 10 layers')
    for name in ('tap_dance', 'combo', 'key_override', 'alt_repeat_key'):
        if len(data[name]) != 32:
            raise ValueError(f'Expected 32 {name} entries')
    if set(data['settings']) != {str(i) for i in range(1, 28) if i != 8}:
        raise ValueError('Unexpected QMK settings IDs for pinned Vial version')
    out = ['// Generated by scripts/vil_defaults_gen.py from vil_backups/default.vil.',
           f'// Source SHA256: {hashlib.sha256(raw).hexdigest()}',
           '#pragma once', '',
           '_Static_assert(DYNAMIC_KEYMAP_LAYER_COUNT == 10, "Default layer count mismatch");',
           '_Static_assert(DYNAMIC_KEYMAP_MACRO_COUNT == 15, "Default macro count mismatch");',
           '_Static_assert(VIAL_TAP_DANCE_ENTRIES == 32 && VIAL_COMBO_ENTRIES == 32 &&',
           '               VIAL_KEY_OVERRIDE_ENTRIES == 32 && VIAL_ALT_REPEAT_KEY_ENTRIES == 32,',
           '               "Vial default entry counts mismatch");', '',
           'const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {']
    for i, layer in enumerate(data['layout']):
        out.append(f'    [{i}] = {{')
        out.extend('        {' + ', '.join(map(keycode, row)) + '},' for row in layer)
        out.append('    },')
    out += ['};', '', 'const uint16_t PROGMEM encoder_map[][NUM_ENCODERS][2] = {']
    for i, layer in enumerate(data['encoder_layout']):
        out.append(f'    [{i}] = {{' + ', '.join('ENCODER_CCW_CW(' + ', '.join(map(keycode, pair)) + ')' for pair in layer) + '},')
    out += ['};', '', 'static const vial_tap_dance_entry_t borne_default_tap_dance[] = {']
    for row in data['tap_dance']:
        if len(row) != 5 or not isinstance(row[4], int) or not 0 <= row[4] <= 65535:
            raise ValueError('Invalid tap dance')
        out.append('    {' + ', '.join([*map(keycode, row[:4]), str(row[4])]) + '},')
    out += ['};', '', 'static const vial_combo_entry_t borne_default_combo[] = {']
    for row in data['combo']:
        if len(row) != 5:
            raise ValueError('Invalid combo')
        out.append('    {{' + ', '.join(map(keycode, row[:4])) + '}, ' + keycode(row[4]) + '},')
    out += ['};']
    for name, ctype, codefields, fields in (
        ('key_override', 'vial_key_override_entry_t', ('trigger', 'replacement'),
         ('layers', 'trigger_mods', 'negative_mod_mask', 'suppressed_mods', 'options')),
        ('alt_repeat_key', 'vial_alt_repeat_key_entry_t', ('keycode', 'alt_keycode'),
         ('allowed_mods', 'options')),
    ):
        out += ['', f'static const {ctype} borne_default_{name}[] = {{']
        for row in data[name]:
            if set(row) != set(codefields + fields):
                raise ValueError(f'Unexpected {name} fields')
            for f in fields:
                if not isinstance(row[f], int) or not 0 <= row[f] <= (65535 if f == 'layers' else 255):
                    raise ValueError(f'Invalid {name}.{f}')
            values = [f'.{f} = {keycode(row[f])}' for f in codefields]
            values += [f'.{f} = {row[f]}' for f in fields]
            out.append('    {' + ', '.join(values) + '},')
        out += ['};']
    out += ['', 'static const struct { uint16_t id; uint32_t value; } borne_default_settings[] = {']
    for sid, value in sorted(data['settings'].items(), key=lambda item: int(item[0])):
        if not isinstance(value, int) or not 0 <= value <= 0xffffffff:
            raise ValueError('Invalid QMK setting')
        out.append(f'    {{{sid}, {value}}},')
    return '\n'.join(out + ['};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=Path('vil_backups/default.vil'))
    parser.add_argument('--output', type=Path, default=Path('source/m57/keymaps/via/vil_defaults.h'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rendered = generate(args.input.read_bytes())
    if args.check:
        if args.output.read_text() != rendered:
            parser.error('Defaults are stale; run python3 scripts/vil_defaults_gen.py')
    else:
        args.output.write_text(rendered)
